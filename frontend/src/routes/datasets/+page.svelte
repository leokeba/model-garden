<script lang="ts">
  import { api } from "$lib/api/client";
  import Button from "$lib/components/Button.svelte";
  import Card from "$lib/components/Card.svelte";
  import {
    DatasetCard,
    HubDatasetCard,
    UploadModal,
    PreviewModal,
  } from "$lib/components/datasets";
  import { onMount } from "svelte";

  type Dataset = {
    name: string;
    path: string;
    size: number;
    examples: number;
    format: string;
    created_at: string;
    modified_at?: string;
    metadata?: Record<string, any>;
  };

  type HubDataset = {
    id: string;
    author: string;
    datasetName: string;
    downloads: number;
    likes: number;
    tags: string[];
    description?: string;
    size?: string;
  };

  let datasets: Dataset[] = $state([]);
